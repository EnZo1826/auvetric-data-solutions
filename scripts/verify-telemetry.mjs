import assert from 'node:assert/strict';
import { initialState, setScenario, step, statusOf } from '../src/lib/telemetry.ts';
let s = initialState();
assert.deepEqual(s, initialState(), 'reset is deterministic');
s = setScenario(s, 'threshold');
for (let i=0;i<20;i++) s=step(s);
assert.equal(s.highActive, true);
s=setScenario(s,'normal');
for(let i=0;i<5;i++) s=step(s);
assert.equal(s.highActive,false);
s=setScenario(s,'sensor'); s=step(s);
assert.equal(s.edge.at(-1).v,null); assert.equal(s.edge.at(-1).q,'bad');
s=setScenario(s,'normal'); s=setScenario(s,'link');
for(let i=0;i<12;i++)s=step(s);
assert.equal(s.buffer.length,12); assert.equal(statusOf(s).stale,true);
s=setScenario(s,'reconnect');
for(let i=0;i<3;i++)s=step(s);
assert.equal(s.buffer.length,0);
assert.ok(s.server.some(p=>p.backfilled));
assert.equal(new Set(s.server.map(p=>p.seq)).size,s.server.length);
console.log('Telemetry: deterministic reset, alarm delay/clear, sensor fault, offline buffer and backfill passed.');
